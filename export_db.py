def load_json_or_jsonl(path: Path) -> Any:
    """Load JSON or JSONL while tolerating empty/invalid lines in JSONL files."""
    if path.suffix.lower() == ".jsonl":
        rows = []
        with open(path, "r", encoding="utf-8") as f:
            for line_no, line in enumerate(f, 1):
                line = line.strip()
                if not line:
                    continue
                try:
                    rows.append(json.loads(line))
                except json.JSONDecodeError as exc:
                    logger.warning(f"Skipping malformed JSONL line {line_no} in {path}: {exc}")
        return rows

    with open(path, "r", encoding="utf-8") as f:
        return json.load(f)


def flatten_history_data(data: Any) -> Any:
    """Convert product_id keyed history dicts into Mongo-friendly documents."""
    if isinstance(data, dict):
        return [{"product_id": str(product_id), "history": history} for product_id, history in data.items()]
    return data


