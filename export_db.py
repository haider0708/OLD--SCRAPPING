def _shop_from_collection(collection_name: str) -> str:
    """Return the shop slug from a collection name like 'tunewtec_products'."""
    if not collection_name:
        return ""
    return collection_name.split("_", 1)[0]


def _is_quota_error(exc: Exception) -> bool:
    """Detect MongoDB Atlas free-tier quota errors."""
    msg = str(exc).lower()
    if (
        "over your space quota" in msg
        or "writes are blocked" in msg
        or ("quota" in msg and "atlas" in msg)
    ):
        return True
    # Atlas free-tier shows code 8000 AtlasError when over quota
    code = getattr(exc, "code", None)
    if code == 8000 and "atlas" in msg:
        return True
    return False


class MongoDBExporter:
    def __init__(self):
        self.local_uri = os.getenv("MONGO_URI_LOCAL") or os.getenv("MONGO_URI_lslsl")
        self.atlas_uri = os.getenv("MONGO_URI")
        self.atlas_uri_new = os.getenv("MONGO_URI_NEW")
        self.db_name = os.getenv("MONGO_DB_NAME", "Retails")
        self.db_name_new = os.getenv("MONGO_DB_NAME_NEW", "Retails")

        # clients is a list of (name, client, db_name, accepts_shop_fn)
        # accepts_shop_fn(shop) returns True if this client should handle that shop.
        self.clients = []
        # Direct ref to the new-cluster client (used as quota-fallback).
        self._fallback_client = None
        self._fallback_db_name = None
        # Once primary cluster is known to be over quota, route all subsequent
        # writes for that cluster directly to the fallback. Avoids per-write
        # quota probing and connection-closed cascades.
        self._primary_over_quota = False

        if MongoClient is None:
            logger.warning(
                "MongoDB export dependencies are not installed; install pymongo[srv] to enable database export."
            )
            return

        # Connect Local
        if self.local_uri:
            try:
                client = MongoClient(self.local_uri, serverSelectionTimeoutMS=2000)
                client.server_info()
                self.clients.append(("local", client, self.db_name, lambda s: True))
                logger.info(f"✅ Connected to Local MongoDB")
            except Exception as e:
                logger.warning(f"⚠️ Could not connect to Local MongoDB: {e}")

        # Connect Atlas (primary) — handles shops NOT in NEW_DB_SHOPS
        if self.atlas_uri:
            try:
                client = MongoClient(
                    self.atlas_uri,
                    serverSelectionTimeoutMS=5000,
                    tlsCAFile=certifi.where(),
                )
                client.server_info()
                self.clients.append((
                    "atlas",
                    client,
                    self.db_name,
                    lambda s: s not in NEW_DB_SHOPS,
                ))
                logger.info(f"✅ Connected to Atlas MongoDB (primary)")
            except Exception as e:
                logger.warning(f"⚠️ Could not connect to Atlas MongoDB: {e}")

        # Connect Atlas (new) — handles only shops in NEW_DB_SHOPS
        # ALSO acts as quota-fallback for the primary cluster.
        if self.atlas_uri_new:
            try:
                client = MongoClient(
                    self.atlas_uri_new,
                    serverSelectionTimeoutMS=5000,
                    tlsCAFile=certifi.where(),
                )
                client.server_info()
                self.clients.append((
                    "atlas-new",
                    client,
                    self.db_name_new,
                    lambda s: s in NEW_DB_SHOPS,
                ))
                # Save for quota-fallback use
                self._fallback_client = client
                self._fallback_db_name = self.db_name_new
                logger.info(f"✅ Connected to Atlas MongoDB (new — for {sorted(NEW_DB_SHOPS)} + quota fallback)")
            except Exception as e:
                logger.warning(f"⚠️ Could not connect to Atlas MongoDB (new): {e}")

        if not self.clients:
            logger.error("❌ No database connections available.")

    def close(self):
        for name, client, _db, _fn in self.clients:
            client.close()
            logger.info(f"Closed {name} connection")

