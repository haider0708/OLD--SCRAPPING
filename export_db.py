    def _write_to_db(self, db, collection_name: str, data, is_history: bool, is_changes: bool, now):
        """Perform the actual write to a database. Raises on failure."""
        from pymongo import UpdateOne
        coll = db[collection_name]

        if is_history:
            ops = []
            for d in data:
                if not isinstance(d, dict):
                    continue
                pid = d.get("product_id")
                if not pid:
                    continue
                d.setdefault("_updated_at", now)
                ops.append(UpdateOne(
                    {"product_id": str(pid)},
                    {"$set": d},
                    upsert=True,
                ))
            if ops:
                coll.bulk_write(ops, ordered=False)
            return ("upserted", len(ops))

        if is_changes:
            ops = []
            for d in data:
                if not isinstance(d, dict):
                    continue
                pid = d.get("product_id")
                detected_at = d.get("detected_at")
                if not pid or not detected_at:
                    continue
                d.setdefault("_updated_at", now)
                ops.append(UpdateOne(
                    {"product_id": str(pid), "detected_at": detected_at},
                    {"$setOnInsert": d},
                    upsert=True,
                ))
            if ops:
                coll.bulk_write(ops, ordered=False)
            return ("appended", len(ops))

        # Full replace for products / details / categories / summaries.
        coll.delete_many({})
        if isinstance(data, list):
            for d in data:
                if isinstance(d, dict):
                    d.setdefault("_updated_at", now)
            if data:
                # Chunk large inserts to avoid connection timeouts on big detail
                # collections (e.g. spacenet has 29K docs ≈ 80MB).
                CHUNK = 500
                for i in range(0, len(data), CHUNK):
                    coll.insert_many(data[i:i + CHUNK], ordered=False)
            return ("exported", len(data))
        elif isinstance(data, dict):
            data.setdefault("_updated_at", now)
            coll.insert_one(data)
            return ("exported", 1)
        return ("exported", 0)

    def export_collection(self, collection_name: str, data: List[Dict]):
        """
        Export documents to a collection.
        - History collections (_history_price, _history_availability): upsert by product_id,
          replacing the history array with the authoritative local version.
        - Change collections (_products_added, _products_removed): append-only by
          product_id + detected_at.
        - All other collections: full replace (delete all + insert all).

        If the primary Atlas cluster rejects a write due to free-tier quota, we
        automatically retry on the new (fallback) cluster so no data is lost.
        """
        if not data:
            return

        is_history = any(
            collection_name.endswith(s)
            for s in ("_history_price", "_history_availability")
        )
        is_changes = any(
            collection_name.endswith(s)
            for s in ("_products_added", "_products_removed")
        )

        shop = _shop_from_collection(collection_name)
        now = datetime.now()

        for name, client, db_name, accepts_shop in self.clients:
            if not accepts_shop(shop):
                continue

            # Sticky fallback: once primary Atlas is known to be over quota,
            # skip it entirely and route directly to atlas-new.
            if (
                name == "atlas"
                and self._primary_over_quota
                and self._fallback_client is not None
            ):
                try:
                    fb_db = self._fallback_client[self._fallback_db_name]
                    verb, count = self._write_to_db(
                        fb_db, collection_name, data, is_history, is_changes, now
                    )
                    logger.info(
                        f"  -> {verb.capitalize()} {count} items to '{collection_name}' on atlas-new (quota-routed)"
                    )
                except Exception as e:
                    logger.error(
                        f"  ❌ atlas-new (quota-routed) failed for '{collection_name}': {e}"
                    )
                continue

            db = client[db_name]
            try:
                verb, count = self._write_to_db(db, collection_name, data, is_history, is_changes, now)
                logger.info(f"  -> {verb.capitalize()} {count} items to '{collection_name}' on {name}")
            except Exception as e:
                # If the primary Atlas cluster is out of space, fall back to the new cluster.
                if (
                    name == "atlas"
                    and _is_quota_error(e)
                    and self._fallback_client is not None
                ):
                    self._primary_over_quota = True  # all future writes go to fallback
                    logger.warning(
                        f"  ⚠️ Primary Atlas over quota — falling back to atlas-new for '{collection_name}' (and all subsequent writes this run)"
                    )
                    try:
                        fb_db = self._fallback_client[self._fallback_db_name]
                        verb, count = self._write_to_db(
                            fb_db, collection_name, data, is_history, is_changes, now
                        )
                        logger.info(
                            f"  -> {verb.capitalize()} {count} items to '{collection_name}' on atlas-new (fallback)"
                        )
                    except Exception as e2:
                        logger.error(
                            f"  ❌ Fallback to atlas-new also failed for '{collection_name}': {e2}"
                        )
                else:
                    logger.error(
                        f"  ❌ Failed to export to '{collection_name}' on {name}: {e}"
                    )

    def _collection_for_path(self, path: Path) -> str:
        """Infer a collection name for ad hoc CLI exports."""
        filename = path.name.lower()
        parent = path.parent.name.lower()

        history_suffixes = {
            "price_history": "_history_price",
            "availability_history": "_history_availability",
            "products_added": "_products_added",
            "products_removed": "_products_removed",
        }
        if parent in history_suffixes:
            return f"{path.stem}{history_suffixes[parent]}"

        shop = self._get_shop_from_path(path)
        if "merged" in filename:
            return "merged_analytics" if "summary" in filename else "merged_products"
        if "products_detailed_summary" in filename:
            return f"{shop}_summary_details"
        if "products_summary" in filename:
            return f"{shop}_summary_products"
        if "products_detailed" in filename:
            return f"{shop}_details"
        if "categories" in filename:
            return f"{shop}_categories"
        if "products" in filename:
            return f"{shop}_products"
        if "summary" in filename:
            return f"{shop}_summary"
        return f"{shop}_other"

    def export_file(self, path: Path):
        """Export one JSON/JSONL file. Used by the CLI entrypoint."""
        if not path.exists():
            logger.error(f"File not found: {path}")
            return
        try:
            data = load_json_or_jsonl(path)
            if path.parent.name in {
                "price_history",
                "availability_history",
                "products_added",
                "products_removed",
            }:
                data = flatten_history_data(data)
            collection = self._collection_for_path(path)
            self.export_collection(collection, data)
        except Exception as e:
            logger.error(f"Failed to export file {path}: {e}")

    def export_directory(self, path: Path):
        """Export all JSON/JSONL files below a directory. Used by the CLI entrypoint."""
        if not path.exists():
            logger.error(f"Directory not found: {path}")
            return

        shop = self._get_shop_from_path(path)
        if shop != "unknown" and (path / "products.json").exists():
            self.export_shop_data(shop, path)
            return

        for fpath in sorted(path.rglob("*")):
            if fpath.suffix.lower() in {".json", ".jsonl"}:
                self.export_file(fpath)

    def export_shop_data(self, shop_name: str, latest_dir: Path):
        """
        Exports all relevant files for a shop to their respective collections.
        """
        logger.info(f"📦 Exporting full data for shop: {shop_name}")

        # Mapping: Filename -> Collection Suffix
        # e.g. products.json -> _products
        file_map = {
            "products.json": "_products",
            "products_detailed.json": "_details",
            "categories.json": "_categories",
            "products_summary.json": "_summary_products",
            "products_detailed_summary.json": "_summary_details",
        }

        for fname, suffix in file_map.items():
            fpath = latest_dir / fname
            if fpath.exists():
                try:
                    data = load_json_or_jsonl(fpath)
                    self.export_collection(f"{shop_name}{suffix}", data)
                except Exception as e:
                    logger.error(f"Failed to load {fname}: {e}")

        for fpath, suffix in history_sources_for_shop(shop_name).items():
            if fpath.exists():
                try:
                    data = flatten_history_data(load_json_or_jsonl(fpath))
                    self.export_collection(f"{shop_name}{suffix}", data)
                except Exception as e:
                    logger.error(f"Failed to export history {fpath.name}: {e}")


